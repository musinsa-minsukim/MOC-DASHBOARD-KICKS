// 날짜가 고정된 공휴일(범위 밖 연도 폴백용). 설·추석·부처님오신날·대체는 제외.
const FIXED = ["01-01", "03-01", "05-05", "06-06", "08-15", "10-03", "10-09", "12-25"];

function dow(iso: string): number {
  const [y, m, d] = iso.split("-").map(Number);
  return new Date(y, m - 1, d).getDay();
}

export function isHolidayKR(iso: string): boolean {
  const d = (iso || "").slice(0, 10);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(d)) return false;
  if (HOLIDAYS.has(d)) return true;
  const y = Number(d.slice(0, 4));
  if (y < RANGE[0] || y > RANGE[1]) return FIXED.includes(d.slice(5)); // 폴백
  return false;
}
export function isSundayISO(iso: string): boolean {
  const d = (iso || "").slice(0, 10);
  return /^\d{4}-\d{2}-\d{2}$/.test(d) && dow(d) === 0;
}
export function isRedDay(iso: string): boolean {
  return isSundayISO(iso) || isHolidayKR(iso);
}

// recharts XAxis 커스텀 틱 — 공휴일/일요일이면 빨강. day=false(주/월 단위)면 색 미적용.
export function HolidayTick(props: any) {
  const { x, y, payload, axisColor = "#94a3b8", day = true, format } = props;
  const raw = String(payload?.value ?? "");
  const iso = /^\d{4}-\d{2}-\d{2}/.test(raw) ? raw.slice(0, 10) : "";
  const red = day && iso && isRedDay(iso);
  const label = format ? format(raw) : raw;
  return (
    <text x={x} y={y} dy={12} textAnchor="middle" fontSize={11} fontWeight={red ? 700 : 400} fill={red ? "#ef4444" : axisColor}>
      {label}
    </text>
  );
}
